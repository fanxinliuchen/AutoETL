-- 1. ETL 目录分类表
CREATE TABLE IF NOT EXISTS t_etl_folder (
    id               BIGINT       NOT NULL COMMENT '主键ID',
    parent_id        BIGINT       NOT NULL DEFAULT 0 COMMENT '父目录ID(0为根)',
    folder_name      VARCHAR(64)  NOT NULL COMMENT '目录名称',
    folder_sort      INT          NOT NULL DEFAULT 0 COMMENT '排序',
    create_user_id   BIGINT       NULL,
    create_user_name VARCHAR(64)  NULL,
    create_time      DATETIME     NULL DEFAULT CURRENT_TIMESTAMP,
    update_user_id   BIGINT       NULL,
    update_user_name VARCHAR(64)  NULL,
    update_time      DATETIME     NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    object_status_cd INT          NOT NULL DEFAULT 0,
    object_version   INT          NOT NULL DEFAULT 1,
    tenant_id        VARCHAR(32)  NULL,
    PRIMARY KEY (id),
    KEY idx_parent_id (parent_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='ETL流程目录表';

-- 2. 数据源连接表
CREATE TABLE IF NOT EXISTS t_etl_datasource (
    id               BIGINT       NOT NULL COMMENT '主键ID',
    ds_name          VARCHAR(64)  NOT NULL COMMENT '数据源名称',
    ds_type          VARCHAR(32)  NOT NULL COMMENT '类型: MYSQL / MYSQL_DW',
    driver_class     VARCHAR(128) NULL     DEFAULT 'com.mysql.cj.jdbc.Driver' COMMENT '驱动类',
    host             VARCHAR(128) NULL     COMMENT '主机',
    port             INT          NULL     DEFAULT 3306 COMMENT '端口',
    database_name    VARCHAR(64)  NULL     COMMENT '数据库名称',
    encoding         VARCHAR(32)  NULL     DEFAULT 'UTF-8' COMMENT '编码',
    jdbc_url         VARCHAR(512) NOT NULL COMMENT 'JDBC连接串',
    username         VARCHAR(64)  NOT NULL COMMENT '用户名',
    password_cipher  VARCHAR(512) NOT NULL COMMENT '加密密码',
    max_pool_size    INT          NOT NULL DEFAULT 5,
    status           TINYINT      NOT NULL DEFAULT 1,
    remark           VARCHAR(255) NULL,
    create_user_id   BIGINT       NULL,
    create_user_name VARCHAR(64)  NULL,
    create_time      DATETIME     NULL DEFAULT CURRENT_TIMESTAMP,
    update_user_id   BIGINT       NULL,
    update_user_name VARCHAR(64)  NULL,
    update_time      DATETIME     NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    object_status_cd INT          NOT NULL DEFAULT 0,
    object_version   INT          NOT NULL DEFAULT 1,
    tenant_id        VARCHAR(32)  NULL,
    PRIMARY KEY (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='ETL数据源配置表';

-- 3. 流程配置主表
CREATE TABLE IF NOT EXISTS t_etl_pipeline (
    id               BIGINT       NOT NULL COMMENT '主键ID',
    folder_id        BIGINT       NULL COMMENT '所属目录ID',
    pipeline_code    VARCHAR(64)  NOT NULL COMMENT '流程编码',
    pipeline_name    VARCHAR(128) NOT NULL COMMENT '流程名称',
    description      VARCHAR(500) NULL,
    source_type      VARCHAR(32)  NOT NULL DEFAULT 'MYSQL' COMMENT 'MYSQL / WEB_API',
    source_ds_id     BIGINT       NULL,
    source_query_sql TEXT         NULL,
    api_url          VARCHAR(512) NULL,
    api_auth_type    VARCHAR(32)  NULL DEFAULT 'NONE',
    api_auth_config  TEXT         NULL,
    api_method       VARCHAR(16)  NULL,
    api_headers      JSON         NULL,
    api_body         TEXT         NULL,
    api_data_path    VARCHAR(128) NULL,
    api_pagination   JSON         NULL,
    transform_sql    MEDIUMTEXT   NULL,
    target_ds_id     BIGINT       NULL,
    target_table     VARCHAR(64)  NULL,
    write_mode       VARCHAR(32)  NOT NULL DEFAULT 'APPEND',
    upsert_keys      VARCHAR(255) NULL,
    field_meta       TEXT         NULL,
    cron_expr        VARCHAR(64)  NULL,
    schedule_status  TINYINT      NOT NULL DEFAULT 0,
    timeout_seconds  INT          NOT NULL DEFAULT 1800,
    max_retry_count  INT          NOT NULL DEFAULT 0,
    alert_config_id  BIGINT       NULL,
    last_run_status  VARCHAR(32)  NULL,
    last_run_time    DATETIME     NULL,
    create_user_id   BIGINT       NULL,
    create_user_name VARCHAR(64)  NULL,
    create_time      DATETIME     NULL DEFAULT CURRENT_TIMESTAMP,
    update_user_id   BIGINT       NULL,
    update_user_name VARCHAR(64)  NULL,
    update_time      DATETIME     NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    object_status_cd INT          NOT NULL DEFAULT 0,
    object_version   INT          NOT NULL DEFAULT 1,
    tenant_id        VARCHAR(32)  NULL,
    PRIMARY KEY (id),
    KEY idx_folder_id (folder_id),
    KEY idx_pipeline_code (pipeline_code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='ETL流程配置表';

-- 4. 任务运行实例表
CREATE TABLE IF NOT EXISTS t_etl_task_instance (
    id               BIGINT       NOT NULL COMMENT '批次ID',
    pipeline_id      BIGINT       NOT NULL,
    pipeline_code    VARCHAR(64)  NOT NULL,
    pipeline_name    VARCHAR(128) NOT NULL,
    trigger_type     VARCHAR(32)  NOT NULL,
    task_status      VARCHAR(32)  NOT NULL,
    start_time       DATETIME     NOT NULL,
    end_time         DATETIME     NULL,
    duration_ms      BIGINT       NULL,
    read_count       BIGINT       NOT NULL DEFAULT 0,
    write_count      BIGINT       NOT NULL DEFAULT 0,
    retry_count      INT          NOT NULL DEFAULT 0,
    error_message    TEXT         NULL,
    log_detail       LONGTEXT     NULL,
    create_user_id   BIGINT       NULL,
    create_user_name VARCHAR(64)  NULL,
    create_time      DATETIME     NULL DEFAULT CURRENT_TIMESTAMP,
    update_user_id   BIGINT       NULL,
    update_user_name VARCHAR(64)  NULL,
    update_time      DATETIME     NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    object_status_cd INT          NOT NULL DEFAULT 0,
    object_version   INT          NOT NULL DEFAULT 1,
    tenant_id        VARCHAR(32)  NULL,
    PRIMARY KEY (id),
    KEY idx_pipeline_time (pipeline_id, start_time DESC)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='ETL执行日志与实例表';

-- 5. 告警配置表
